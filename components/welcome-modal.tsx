"use client";

import { useState, useEffect } from "react";
import {
    Dialog,
    DialogContent,
    DialogDescription,
    DialogFooter,
    DialogHeader,
    DialogTitle,
} from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";

export default function WelcomeModal() {
    const [isOpen, setIsOpen] = useState(false);

    useEffect(() => {
        // Check if the user has seen the modal before
        const hasSeenModal = localStorage.getItem("hasSeenWelcomeModal");

        if (!hasSeenModal) {
            setIsOpen(true);
        }
    }, []);

    const handleClose = () => {
        // Save to localStorage that the user has seen the modal
        localStorage.setItem("hasSeenWelcomeModal", "true");
        setIsOpen(false);
    };

    return (
        <Dialog open={isOpen} onOpenChange={setIsOpen}>
            <DialogContent className="sm:max-w-md">
                <DialogHeader>
                    <DialogTitle>Welcome to EzSchema</DialogTitle>
                    <DialogDescription>
                        Important information about AI-generated content
                    </DialogDescription>
                </DialogHeader>
                <div className="space-y-4">
                    <p>
                        Please be aware that the content generated by AI may not always be accurate or complete.
                    </p>
                    <p className="font-semibold text-amber-600">
                        Always double-check any edits or suggestions made by the AI before using them in your resume.
                    </p>
                    <p>
                        To get started, upload your resume PDF and we'll help you optimize it.
                    </p>
                </div>
                <DialogFooter>
                    <Button onClick={handleClose} className="w-full">
                        I understand, let's continue
                    </Button>
                </DialogFooter>
            </DialogContent>
        </Dialog>
    );
} 